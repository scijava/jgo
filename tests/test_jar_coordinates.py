"""
Tests for inferring the Maven coordinates a JAR file was built from.
"""

import zipfile
from pathlib import Path

from jgo.env import embedded_pom_entries, jar_coordinates, read_embedded_pom

# =============================================================================
# Test fixtures - build JARs on disk, since the name is part of the evidence
# =============================================================================

POM_TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
{body}
</project>
"""


def pom_xml(groupId=None, artifactId=None, version=None, parent_version=None) -> str:
    """Build POM XML content, with the version optionally inherited from a parent."""
    lines = []
    if parent_version:
        lines.append(
            f"  <parent>\n"
            f"    <groupId>{groupId}</groupId>\n"
            f"    <artifactId>{artifactId}-parent</artifactId>\n"
            f"    <version>{parent_version}</version>\n"
            f"  </parent>"
        )
    if groupId:
        lines.append(f"  <groupId>{groupId}</groupId>")
    if artifactId:
        lines.append(f"  <artifactId>{artifactId}</artifactId>")
    if version:
        lines.append(f"  <version>{version}</version>")
    return POM_TEMPLATE.format(body="\n".join(lines))


def make_jar(
    tmp_path: Path,
    filename: str,
    *,
    poms: dict[tuple[str, str], str] | None = None,
    properties: dict[tuple[str, str], str] | None = None,
    manifest: str | None = None,
) -> Path:
    """
    Write a JAR containing the given Maven metadata and manifest.

    Args:
        tmp_path: Directory to write the JAR into
        filename: Name of the JAR file
        poms: (groupId, artifactId) -> pom.xml content
        properties: (groupId, artifactId) -> pom.properties content
        manifest: MANIFEST.MF content
    """
    jar_path = tmp_path / filename
    with zipfile.ZipFile(jar_path, "w") as jar:
        if manifest:
            jar.writestr("META-INF/MANIFEST.MF", manifest)
        for (groupId, artifactId), content in (poms or {}).items():
            jar.writestr(f"META-INF/maven/{groupId}/{artifactId}/pom.xml", content)
        for (groupId, artifactId), content in (properties or {}).items():
            jar.writestr(
                f"META-INF/maven/{groupId}/{artifactId}/pom.properties", content
            )
        jar.writestr("org/example/Thing.class", b"\xca\xfe\xba\xbe")
    return jar_path


def pom_properties(groupId: str, artifactId: str, version: str) -> str:
    """Build pom.properties content in the format Maven writes it."""
    return (
        "#Generated by Maven\n"
        f"groupId={groupId}\n"
        f"artifactId={artifactId}\n"
        f"version={version}\n"
    )


